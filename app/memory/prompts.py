# 执行事实提取：

# 1. 先筛选长期价值，再核对主体、陈述者、来源、适用范围与证据边界；不合格候选直接舍弃。
# 2. 从本次提供的原始资料中提取明确支持的结论，不补造用户画像、动机、因果、经历或长期习惯。
# 3. 一个独立结论形成一条事实。同一结论的重复表述合并；不同主体、范围或证据状态不能因主题相近而合并。
# 4. 可以提炼单次任务中明确支持的可复用经验，但不能仅凭一次成功就概括为普遍有效的方法。
# 5. 提取不承担跨历史事实的最终裁决：保留本次陈述的来源与状态，供后续归纳比较。
